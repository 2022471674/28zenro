#: 攻击探测载荷
_ATTACK_PAYLOADS = (
    "?id=1' AND 1=1-- -",
    "?id=1' OR '1'='1",
    "?q=<script>alert(1)</script>",
    "?cmd=cat%20/etc/passwd",
    "?file=../../etc/passwd",
)

#: 拦截页通用关键词
_GENERIC_BLOCK_MARKERS = (
    "waf", "blocked", "forbidden", "intercept", "拦截", "被拦截",
    "access denied", "not acceptable", "攻击", "attack",
)


def _session() -> requests.Session:
    """创建走全局代理池的请求会话（Web 工具统一入口）。"""
    from lib import proxy_pool

    session = proxy_pool.make_session("waf_detect")
    session.headers.update({"User-Agent": USER_AGENT, "Connection": "close"})
    return session


def normalize_url(raw: str) -> str:
    """补协议头、去首尾空白、校验 netloc。"""
    from urllib.parse import urlparse

    text = str(raw or "").strip().replace("：", ":")
    if not text:
        raise WafDetectError("请填写目标 URL，如 https://example.com")
    if "://" not in text:
        text = "http://" + text
    if not urlparse(text).hostname:
        raise WafDetectError("目标格式不正确，示例：https://example.com")
    return text


def _fetch(session: requests.Session, url: str, timeout: float) -> tuple[int, dict, bytes]:
    """请求一次，返回 (status, headers, body)。"""
    response = session.get(url, timeout=timeout, verify=False,
                           allow_redirects=True, stream=True)
    status = response.status_code
    headers = dict(response.headers)
    body = response.content[:128 * 1024]
    response.close()
    return status, headers, body


def _match_rule(headers: dict[str, str], body: str, status: int,
                rule: dict[str, Any]) -> bool:
    """判断单个 WAF 规则是否命中。"""
    lowered_headers = {k.lower(): v.lower() for k, v in headers.items()}
    for key, needle in rule.get("headers", {}).items():
        if not needle:
            if key in lowered_headers:
                return True
            continue
        if key in lowered_headers and needle in lowered_headers[key]:
            return True
    set_cookie = lowered_headers.get("set-cookie", "")
    for cookie in rule.get("cookies", []):
        if cookie.lower() in set_cookie:
            return True
    for marker in rule.get("body", []):
        if marker.lower() in body:
            return True
    if status in rule.get("status", []):
        return True
    return False


def run(
    target: str,
    timeout: float = DEFAULT_TIMEOUT,
    log: LogFn | None = None,
    stop: threading.Event | None = None,
) -> dict[str, Any]:
    """对 ``target`` 做 WAF 识别，返回结构化结果。

    返回
    ----
    ``{"target","normal_status","attack_results":[...],
       "matches":[{name,bypass}], "blocked":bool}``。
    """
    emit = log or (lambda _m: None)
    base = normalize_url(target)
    emit(f"[目标] {base}")
    session = _session()

    try:
        norm_status, norm_headers, norm_body = _fetch(session, base, timeout)
    except requests.RequestException as exc:
        session.close()
        raise WafDetectError(f"目标连接失败：{exc}") from exc
    emit(f"[基线] 正常请求状态码 {norm_status}，正文 {len(norm_body)} 字节")

    # 攻击请求探测
    attack_results: list[dict[str, Any]] = []
    for payload in _ATTACK_PAYLOADS:
        if stop is not None and stop.is_set():
            break
        url = base.rstrip("/") + payload
        try:
            status, headers, body = _fetch(session, url, timeout)
        except requests.RequestException as exc:
            attack_results.append({"payload": payload, "status": 0,
                                   "note": f"请求失败：{exc}"})
            continue
        attack_results.append({
            "payload": payload, "status": status,
            "blocked": status != norm_status or status >= 400,
            "note": "" if status == norm_status
            else f"状态码变化 {norm_status}->{status}",
        })

    # 用带通用特征的攻击请求拿完整响应做指纹匹配
    try:
        probe_url = base.rstrip("/") + "?id=1' AND 1=1-- -"
        p_status, p_headers, p_body = _fetch(session, probe_url, timeout)
    except requests.RequestException:
        p_status, p_headers, p_body = norm_status, norm_headers, b""
    body_text = p_body.decode("utf-8", "ignore").lower()

    matches: list[dict[str, Any]] = []
    seen_names: set[str] = set()
    for rule in _WAF_RULES:
        if _match_rule(p_headers, body_text, p_status, rule):
            if rule["name"] not in seen_names:
                seen_names.add(rule["name"])
                matches.append({
                    "name": rule["name"],
                    "bypass": rule["bypass"],
                    "match_type": "response",
                })

    blocked = p_status != norm_status and p_status >= 400
    if blocked and not matches:
        for marker in _GENERIC_BLOCK_MARKERS:
            if marker in body_text:
                matches.append({
                    "name": "未知 WAF / 拦截设备",
                    "bypass": ["尝试常见编码绕过", "变换请求头模拟真实浏览器"],
                    "match_type": "generic",
                })
                break

    session.close()
    emit(f"[结果] 命中 {len(matches)} 个 WAF 指纹"
         + (f"，拦截行为 {'有' if blocked else '无'}"))
    return {
        "target": base,
        "normal_status": norm_status,
        "attack_results": attack_results,
        "matches": matches,
        "blocked": blocked,
    }


