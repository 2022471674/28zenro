"""WAF 识别与绕过辅助：识别常见 Web 应用防火墙并给出绕过建议。

通过向目标发送带「明显攻击特征」的探测载荷，对比正常请求与攻击请求在
状态码 / 响应头 / 响应体上的差异，再结合已知 WAF 响应特征识别厂商，并附带
常见绕过建议。纯手写、无第三方依赖。

识别维度：响应头特征、拦截页关键词、状态码差异。

设计约定：请求统一经 ``proxy_pool.make_session()``；只做纯逻辑；支持
``stop`` 与逐行日志。
"""

